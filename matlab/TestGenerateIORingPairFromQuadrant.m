%% Test GenerateIORingPairFromQuadrant using BIGBLACK_IOring_MagnetOnly
% as the starting geometry.

Fov_half = 75;
%Fov_half = 10;


FOV_half_1 = Fov_half;
FOV_1 = -FOV_half_1:1:FOV_half_1;
FOV_half_2 = Fov_half;
FOV_2 = -FOV_half_2:1:FOV_half_2;
FOV_3 = 0;
surface = 'z';
n_per_group = 1;
font_size = 18;

% Original BIGBLACK inputs.
n_bar = 33;


% The same row number across these four arrays describes one seed magnet.
%   quadrant_loc   : [R, Z] in mm
%   quadrant_dim   : local [dim_x, dim_y, dim_z] in mm
%   quadrant_angle : magnetization angle in the R-Z plane, in degrees
%   quadrant_Br    : remanence in T
%
% The upper ring points radially outward (+R, 180 deg). The new function
% automatically creates the complete upper ring and the inward-pointing
% lower ring, giving the same physical IOring pair as the original test.

% radial, Z
quadrant_loc = [ ...
    172, 255; ...
    144, 255; ...
    130, 255; ...
    116, 255; ...
    172, 221; ...
    158, 221; ...
    144, 221; ...
    130, 221; ...
    116, 221; ...
    158, 187; ...
    144, 187; ...
