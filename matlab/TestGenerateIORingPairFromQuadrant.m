    116, 187; ...
    172, 153; ...
    158, 153; ...
    144, 153; ...
    130, 153; ...
    116, 153; ...
    158, 119; ...
    130, 119; ...
    116, 119; ...
    130,  85; ...
    116,  85; ...
    158,  51; ...
    144,  51; ...
    130,  51; ...
    158,  17; ...
    144,  17];

quadrant_angle = [ ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
    180; ...
