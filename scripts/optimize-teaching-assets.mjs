import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { gzipSync, gunzipSync } from "node:zlib";

// Lossless transport optimization only. The original GLB, every registration
// matrix and all scene identity/guide fields remain unchanged.
const project = path.resolve(import.meta.dirname, "..");
const publicDirectory = path.join(project, "public");
const cacheDirectory = path.join(publicDirectory, "assembly", "cache");
const source = JSON.parse(await readFile(path.join(publicDirectory, "assembly", "manifest.json"), "utf8"));
const sha256 = bytes => createHash("sha256").update(bytes).digest("hex");
let reusedFiles = 0;

async function writeIfChanged(filename, bytes) {
  const expected = Buffer.isBuffer(bytes) ? bytes : Buffer.from(bytes);
  try {
    if ((await readFile(filename)).equals(expected)) {
      reusedFiles++;
      return;
    }
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await mkdir(path.dirname(filename), { recursive: true });
  await writeFile(filename, expected);
}

function selectRuntimeFields(asset) {
  const result = {};
  for (const field of ["id", "ring", "sourceToCanonical"])
    if (asset[field] !== undefined) result[field] = asset[field];
  if (asset.registration) result.registration = {
    axis: asset.registration.axis,
    phaseCorrectionDeg: asset.registration.phaseCorrectionDeg,
  };
  for (const guide of ["jointGuide", "closureGuide"])
    if (asset[guide]) result[guide] = { direction: asset[guide].direction };
  if (asset.nodes) result.nodes = asset.nodes.map(node => ({
    name: node.name,
    ...(node.role !== undefined ? { role: node.role } : {}),
    ...(node.quarter !== undefined ? { quarter: node.quarter } : {}),
  }));
  return result;
}

async function optimize(asset) {
  const filename = path.resolve(publicDirectory, "." + asset.url);
  if (!filename.startsWith(publicDirectory + path.sep)) throw new Error("CAD URL is outside public assets.");
  const original = await readFile(filename);
  assert.equal(original.readUInt32LE(0), 0x46546c67, `${asset.url}: GLB header`);
  assert.equal(original.readUInt32LE(8), original.length, `${asset.url}: GLB length`);
  const hash = sha256(original);
  if (asset.sha256) assert.equal(hash, asset.sha256, `${asset.url}: source hash`);
  const compressed = gzipSync(original, { level: 9 });
  assert.deepEqual(gunzipSync(compressed), original, `${asset.url}: lossless gzip round-trip`);
  const stem = path.basename(asset.url, ".glb");
  const rawName = `${stem}.${hash}.glb`;
  const gzipName = `${stem}.${sha256(compressed)}.glb.gz`;
  await writeIfChanged(path.join(cacheDirectory, rawName), original);
  await writeIfChanged(path.join(cacheDirectory, gzipName), compressed);
  return {
    ...selectRuntimeFields(asset),
    url: `/assembly/cache/${rawName}`,
    gzipURL: `/assembly/cache/${gzipName}`,
    sha256: hash,
    bytes: original.length,
    gzipBytes: compressed.length,
  };
}

await mkdir(cacheDirectory, { recursive: true });
const layers = await Promise.all(source.layers.map(optimize));
const parts = await Promise.all((source.parts || []).map(optimize));
const runtime = {
  schemaVersion: source.schemaVersion,
  unit: source.unit,
  geometryVersion: source.geometryVersion,
  layers,
  parts,
  rodAxes: (source.rodAxes || []).map(axis => ({ x: axis.x, y: axis.y })),
};
const runtimeBytes = Buffer.from(JSON.stringify(runtime));
const runtimeURL = `/assembly/cache/runtime.${sha256(runtimeBytes)}.json`;
await writeIfChanged(path.join(publicDirectory, runtimeURL), runtimeBytes);
await writeIfChanged(path.join(project, "lib", "assembly-assets.generated.ts"),
  `// Generated by scripts/optimize-teaching-assets.mjs.\n// Only content-hashed assets receive immutable browser caching.\nexport const ASSEMBLY_RUNTIME_MANIFEST_URL = ${JSON.stringify(runtimeURL)};\n`);

const overview = [...layers, ...parts.filter(asset => /support|locator/.test(asset.id))];
console.log(JSON.stringify({
  assets: layers.length + parts.length,
  losslessGLBChecks: layers.length + parts.length,
  runtimeManifestBytes: runtimeBytes.length,
  originalManifestBytes: (await readFile(path.join(publicDirectory, "assembly", "manifest.json"))).length,
  overviewRawBytes: overview.reduce((sum, asset) => sum + asset.bytes, 0),
  overviewGzipBytes: overview.reduce((sum, asset) => sum + asset.gzipBytes, 0),
  reusedFiles,
  runtimeURL,
}));
